const clean=s=>s.replace(/<!--[sS]*?-->/g,'').replace(/s(width|height|class)="[^"]*"/g,'').replace('<svg','<svg aria-hidden="true" focusable="false"').trim();
const cache={};
// icon('crown') → <svg class="ic">; icon('crown','extra',true) usa la versión rellena. El tamaño lo da el CSS (1.25em).
export function icon(name,cls='',filled=false){
  const raw=(filled&&FILL[name])||BOLD[name];if(!raw)return '';
  const key=(filled&&FILL[name]?'f:':'b:')+name;
  cache[key]=cache[key]||clean(raw);
  return cache[key].replace('<svg','<svg class="ic'+(cls?' '+cls:'')+'"');
}
